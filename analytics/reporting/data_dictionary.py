"""Generate docs/data_dictionary.md from the live database + dbt manifest.

Column names and types come from information_schema (what actually exists);
descriptions and grain come from the dbt YAML (via target/manifest.json).
Run `dbt build` (or `dbt parse`) first so the manifest is current.

Usage:  python -m analytics.reporting.data_dictionary
"""

from __future__ import annotations

import json

from analytics.metrics.db import read_sql
from config.settings import PROJECT_ROOT

MANIFEST = PROJECT_ROOT / "dbt_project" / "target" / "manifest.json"
OUT = PROJECT_ROOT / "docs" / "data_dictionary.md"
SCHEMAS = ["marts", "reporting", "intermediate", "staging", "reference"]


def main() -> None:
    manifest = json.loads(MANIFEST.read_text())
    docs: dict[tuple[str, str], dict] = {}
    for node in manifest["nodes"].values():
        if node["resource_type"] in ("model", "seed"):
            docs[(node["schema"], node["name"])] = node
    cols = read_sql("""
        select c.table_schema, c.table_name, c.column_name, c.data_type, c.ordinal_position,
               coalesce(s.n_live_tup, 0) as approx_rows
        from information_schema.columns c
        left join pg_stat_user_tables s
          on s.schemaname = c.table_schema and s.relname = c.table_name
        where c.table_schema = any(:schemas)
        order by c.table_schema, c.table_name, c.ordinal_position""",
                    {"schemas": SCHEMAS})
    counts = {}
    for schema, table in cols[["table_schema", "table_name"]].drop_duplicates().itertuples(index=False):
        counts[(schema, table)] = int(read_sql(f'select count(*) n from "{schema}"."{table}"').n[0])

    lines = ["# Data Dictionary", "",
             "_Generated by `python -m analytics.reporting.data_dictionary` from the live "
             "PostgreSQL catalog (columns, types, row counts) and the dbt project's YAML "
             "(descriptions, grain). Raw-layer columns follow the official MIMIC-IV schema; "
             "see [config/sources.yaml](../config/sources.yaml)._", "",
             "Layers: `raw` (source, typed) → `staging` (views: rename/type/flag) → "
             "`intermediate` (business logic) → `marts` (star schema) → `reporting` "
             "(aggregate views). `reference` holds dbt seeds.", ""]
    for schema in SCHEMAS:
        tables = cols[cols.table_schema == schema].table_name.unique()
        if not len(tables):
            continue
        lines += [f"## Schema `{schema}`", ""]
        for table in tables:
            node = docs.get((schema, table), {})
            desc = " ".join((node.get("description") or "").split())
            lines += [f"### `{schema}.{table}`", ""]
            if desc:
                lines += [desc, ""]
            lines += [f"Rows (demo): {counts[(schema, table)]:,}", "",
                      "| Column | Type | Description |", "|---|---|---|"]
            col_docs = node.get("columns", {})
            for r in cols[(cols.table_schema == schema) & (cols.table_name == table)].itertuples():
                cdesc = " ".join((col_docs.get(r.column_name, {}).get("description") or "").split())
                lines.append(f"| `{r.column_name}` | {r.data_type} | {cdesc} |")
            lines.append("")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
