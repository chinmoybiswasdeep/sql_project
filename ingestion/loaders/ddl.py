"""Generate raw-layer DDL from the source contract (single source of truth)."""

from __future__ import annotations

import hashlib
import json
from typing import Any

from config.settings import PROJECT_ROOT, load_source_contract


def contract_hash(table_spec: dict[str, Any]) -> str:
    """Stable hash of a table's contract; a change forces a reload on restart."""
    canonical = json.dumps(table_spec, sort_keys=True)
    return hashlib.sha256(canonical.encode()).hexdigest()[:16]


def create_table_sql(name: str, spec: dict[str, Any]) -> str:
    cols = ",\n".join(f"    {col:<22} {typ}" for col, typ in spec["columns"].items())
    return (
        f"CREATE TABLE IF NOT EXISTS raw.{name} (\n{cols},\n"
        f"    _source_line           bigint NOT NULL,\n"
        f"    _ingestion_run_id      bigint NOT NULL\n);"
    )


def render_all() -> str:
    contract = load_source_contract()
    header = (
        "-- GENERATED by ingestion/loaders/ddl.py from config/sources.yaml. Do not edit.\n"
        "-- Raw tables carry two lineage columns: _source_line, _ingestion_run_id.\n"
        "-- No constraints are enforced here: keys and relationships are *measured*\n"
        "-- at load time and by dbt tests, so bad source rows are visible, not hidden.\n\n"
    )
    return header + "\n\n".join(
        create_table_sql(name, contract["tables"][name]) for name in contract["load_order"]
    ) + "\n"


if __name__ == "__main__":
    out = PROJECT_ROOT / "database" / "schemas" / "002_raw_tables.sql"
    out.write_text(render_all())
    print(f"wrote {out}")
