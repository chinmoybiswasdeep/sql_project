"""End-to-end raw ingestion: schemas -> per-table load -> checks -> indexes -> report.

Usage:
    python -m ingestion.pipelines.run_ingestion                # demo, all tables
    python -m ingestion.pipelines.run_ingestion --force        # reload unchanged tables
    python -m ingestion.pipelines.run_ingestion --tables patients admissions
    HI_DATASET_MODE=full python -m ingestion.pipelines.run_ingestion --skip-optional

Exit code is non-zero if any table fails or any error-severity check fails.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from datetime import UTC, datetime

import psycopg

from config.settings import PROJECT_ROOT, get_settings, load_source_contract
from ingestion.loaders.ddl import render_all
from ingestion.loaders.postgres_loader import TableLoadResult, load_table
from ingestion.logging_utils import get_logger
from ingestion.validators.quality import run_checks

log = get_logger("ingestion.pipeline")
REPORT_DIR = PROJECT_ROOT / "reports" / "ingestion"


def apply_sql_file(conn: psycopg.Connection, path) -> None:
    with conn.cursor() as cur:
        cur.execute(path.read_text())
    conn.commit()


def record_table(conn: psycopg.Connection, run_id: int, r: TableLoadResult) -> None:
    with conn.cursor() as cur:
        cur.execute(
            """INSERT INTO meta.ingestion_table_log
               (run_id, table_name, source_file, file_sha256, contract_hash, status, source_rows,
                loaded_rows, rejected_rows, duplicate_key_rows, orphan_rows, extra_columns,
                duration_seconds, error_message)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
            (run_id, r.table, r.source_file, r.file_sha256, r.contract_hash, r.status,
             r.source_rows, r.loaded_rows, r.rejected_rows, r.duplicate_key_rows,
             json.dumps(r.orphan_rows), r.extra_columns, round(r.duration_seconds, 3),
             r.error_message),
        )
    conn.commit()


def write_report(run_id: int, settings, results: list[TableLoadResult], checks: list[dict],
                 status: str, conn: psycopg.Connection) -> None:
    """Aggregate-only report (no patient-level values) in Markdown and JSON."""
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    with conn.cursor() as cur:
        # Latest profile per column: skipped (unchanged) tables keep their last profile.
        cur.execute(
            """SELECT table_name, column_name, null_pct FROM (
                 SELECT DISTINCT ON (table_name, column_name) table_name, column_name, null_pct
                 FROM meta.column_profile ORDER BY table_name, column_name, run_id DESC) p
               WHERE null_pct > 0 ORDER BY table_name, null_pct DESC"""
        )
        missing = cur.fetchall()
    generated = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    payload = {
        "run_id": run_id, "dataset": settings.dataset_label, "mode": settings.dataset_mode,
        "status": status, "generated_at": generated,
        "tables": [asdict(r) for r in results], "checks": checks,
        "missingness": [{"table": t, "column": c, "null_pct": float(p)} for t, c, p in missing],
    }
    (REPORT_DIR / "ingestion_report.json").write_text(json.dumps(payload, indent=2, default=str))

    lines = [
        "# Ingestion Report", "",
        f"- **Run ID:** {run_id}", f"- **Dataset:** `{settings.dataset_label}` "
        f"({settings.dataset_mode} mode)", f"- **Status:** {status}",
        f"- **Generated:** {generated}", "",
        "Generated by `python -m ingestion.pipelines.run_ingestion`. All figures come from "
        "this run's audit tables (`meta.*`).", "",
        "## Row-count reconciliation", "",
        "| Table | Status | Source rows | Loaded | Rejected | Dup-key rows | Orphans | Seconds |",
        "|---|---|---:|---:|---:|---:|---|---:|",
    ]
    for r in results:
        orphans = ", ".join(f"{k}: {v}" for k, v in r.orphan_rows.items() if v) or "0"
        lines.append(
            f"| {r.table} | {r.status} | {r.source_rows:,} | {r.loaded_rows:,} | "
            f"{r.rejected_rows:,} | {r.duplicate_key_rows:,} | {orphans} | "
            f"{r.duration_seconds:.2f} |"
        )
    lines += ["", "Skipped tables were unchanged since their last successful load (same file "
              "SHA-256 and contract) and were not re-read: Source rows shows 0 and Loaded "
              "shows the row count still in the table from that load.", "",
              "## Plausibility checks (flagged, never deleted)", "",
              "| Check | Table | Severity | Status | Flagged rows | Description |",
              "|---|---|---|---|---:|---|"]
    for c in checks:
        lines.append(f"| `{c['check']}` | {c['table']} | {c['severity']} | {c['status']} | "
                     f"{c['flagged_rows']:,} | {c['description']} |")
    lines += ["", "## Missingness (columns with any nulls)", "",
              "| Table | Column | Null % |", "|---|---|---:|"]
    lines += [f"| {t} | {c} | {float(p):.1f} |" for t, c, p in missing]
    if not missing:
        lines.append("| — | — | — |")
    (REPORT_DIR / "ingestion_report.md").write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Load MIMIC-IV into PostgreSQL raw schema")
    parser.add_argument("--tables", nargs="*", help="subset of tables (default: all)")
    parser.add_argument("--force", action="store_true", help="reload even if unchanged")
    parser.add_argument("--skip-optional", action="store_true",
                        help="skip tables marked optional (e.g. chartevents)")
    args = parser.parse_args(argv)

    settings = get_settings()
    contract = load_source_contract()
    order = [t for t in contract["load_order"] if not args.tables or t in args.tables]
    if args.skip_optional:
        order = [t for t in order if not contract["tables"][t].get("optional")]
    if not settings.data_dir.exists():
        log.error("dataset directory missing", extra={"path": str(settings.data_dir)})
        return 2

    with psycopg.connect(settings.pg.conninfo) as conn:
        apply_sql_file(conn, PROJECT_ROOT / "database" / "schemas" / "001_schemas.sql")
        with conn.cursor() as cur:
            cur.execute(render_all())
            cur.execute(
                "INSERT INTO meta.ingestion_runs (dataset_label, dataset_mode) VALUES (%s, %s)"
                " RETURNING run_id", (settings.dataset_label, settings.dataset_mode))
            run_id = cur.fetchone()[0]
        conn.commit()
        log.info("run started", extra={"run_id": run_id, "dataset": settings.dataset_label,
                                       "tables": len(order)})

        results: list[TableLoadResult] = []
        for table in order:
            spec = contract["tables"][table]
            r = load_table(conn, run_id, table, spec, settings.data_dir, settings.batch_rows,
                           full_mode=settings.dataset_mode == "full", force=args.force)
            if r.status == "skipped_missing" and not spec.get("optional"):
                r.status = "failed"
            record_table(conn, run_id, r)
            results.append(r)
            level = log.error if r.status == "failed" else log.info
            level("table processed", extra={
                "table": table, "status": r.status, "source_rows": r.source_rows,
                "loaded_rows": r.loaded_rows, "rejected_rows": r.rejected_rows,
                "duplicate_key_rows": r.duplicate_key_rows, "orphans": r.orphan_rows,
                "seconds": round(r.duration_seconds, 2), "error": r.error_message})

        apply_sql_file(conn, PROJECT_ROOT / "database" / "indexes" / "001_raw_indexes.sql")
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute("ANALYZE")
        conn.autocommit = False

        checks = run_checks(conn, run_id)
        failed_tables = [r.table for r in results if r.status == "failed"]
        failed_checks = [c["check"] for c in checks if c["status"] == "fail"]
        status = "failed" if failed_tables else ("partial" if failed_checks else "succeeded")
        with conn.cursor() as cur:
            cur.execute("UPDATE meta.ingestion_runs SET finished_at = now(), status = %s,"
                        " notes = %s WHERE run_id = %s",
                        (status, json.dumps({"failed_tables": failed_tables,
                                             "failed_checks": failed_checks}), run_id))
        conn.commit()
        write_report(run_id, settings, results, checks, status, conn)
        log.info("run finished", extra={"run_id": run_id, "status": status,
                                        "failed_tables": failed_tables,
                                        "failed_checks": failed_checks})
    return 0 if status == "succeeded" else 1


if __name__ == "__main__":
    sys.exit(main())
