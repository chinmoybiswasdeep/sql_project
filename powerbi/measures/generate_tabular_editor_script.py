"""Generate a Tabular Editor C# script from measures.dax.

    .venv/bin/python -m powerbi.measures.generate_tabular_editor_script

measures.dax is the single source of truth. Each measure is preceded by
``// @folder=<folder> @format=<format>`` and comment lines (the description).
The generated ``measures_tabular_editor.csx`` creates or updates every measure
in the '_Measures' table with its expression, display folder, format string and
description. Run it in Tabular Editor 2/3 (C# Script tab) connected to the open
Power BI Desktop model, then save the model (Ctrl+S).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
DAX_PATH = HERE / "measures.dax"
CSX_PATH = HERE / "measures_tabular_editor.csx"

_ANNOTATION = re.compile(r"^\s*//\s*@folder=(?P<folder>.*?)\s+@format=(?P<format>.*)$")
_MEASURE = re.compile(r"^\s*MEASURE\s+'(?P<table>[^']+)'\[(?P<name>[^\]]+)\]\s*=\s*(?P<rest>.*)$")


@dataclass
class Measure:
    table: str
    name: str
    expression: str
    folder: str
    format_string: str
    description: str


def parse_measures(text: str) -> list[Measure]:
    lines = text.splitlines()
    body_end = next(i for i, ln in enumerate(lines) if ln.strip().startswith("EVALUATE"))
    measures: list[Measure] = []
    i = 0
    while i < body_end:
        ann = _ANNOTATION.match(lines[i])
        if not ann:
            i += 1
            continue
        desc: list[str] = []
        i += 1
        while not _MEASURE.match(lines[i]):
            desc.append(lines[i].strip().removeprefix("//").strip())
            i += 1
        head = _MEASURE.match(lines[i])
        expr = [head.group("rest")] if head.group("rest").strip() else []
        i += 1
        while i < body_end and lines[i].strip() and not _ANNOTATION.match(lines[i]) \
                and not lines[i].strip().startswith("// ===="):
            expr.append(lines[i])
            i += 1
        expression = _dedent("\n".join(expr))
        measures.append(Measure(head.group("table"), head.group("name"), expression,
                                ann.group("folder").strip(), ann.group("format").strip(),
                                " ".join(d for d in desc if d)))
    names = [m.name for m in measures]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        raise ValueError(f"Duplicate measure names: {sorted(dupes)}")
    return measures


def _dedent(block: str) -> str:
    rows = block.splitlines()
    indents = [len(r) - len(r.lstrip()) for r in rows[1:] if r.strip()]
    cut = min(indents) if indents else 0
    return "\n".join([rows[0].strip()] + [r[cut:] for r in rows[1:]]) if rows else ""


def _cs(value: str) -> str:
    """C# verbatim string literal."""
    return '@"' + value.replace('"', '""') + '"'


def render_csx(measures: list[Measure]) -> str:
    out = [
        "// Generated by powerbi/measures/generate_tabular_editor_script.py from measures.dax.",
        "// Do not edit by hand: edit measures.dax and regenerate.",
        "// Tabular Editor 2/3 > C# Script > paste > Run (F5), then File > Save (Ctrl+S).",
        "// Creates or updates measures in the '_Measures' table (create it first via",
        "// Power Query; see power_query.m).",
        'var t = Model.Tables["_Measures"];',
        "Measure m;",
    ]
    for ms in measures:
        out += [
            "",
            f"// {ms.folder} / {ms.name}",
            f"m = t.Measures.Contains({_cs(ms.name)}) ? t.Measures[{_cs(ms.name)}]"
            f" : t.AddMeasure({_cs(ms.name)});",
            f"m.Expression = {_cs(ms.expression)};",
            f"m.DisplayFolder = {_cs(ms.folder)};",
            f"m.FormatString = {_cs(ms.format_string)};",
            f"m.Description = {_cs(ms.description)};",
        ]
    out += ["", f'Info("Created or updated {len(measures)} measures in _Measures.");', ""]
    return "\n".join(out)


def main() -> int:
    measures = parse_measures(DAX_PATH.read_text())
    CSX_PATH.write_text(render_csx(measures))
    folders: dict[str, int] = {}
    for m in measures:
        folders[m.folder] = folders.get(m.folder, 0) + 1
    print(f"Wrote {CSX_PATH.name}: {len(measures)} measures")
    for folder, n in folders.items():
        print(f"  {folder:<24} {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
