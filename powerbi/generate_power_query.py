"""Generate powerbi/documentation/power_query.m from the export specs and manifest.

    .venv/bin/python -m powerbi.generate_power_query [--manifest powerbi/datasets/manifest.json]

The column list and Power Query type of every column come from manifest.json,
which the export script writes from the PostgreSQL result types. The native SQL
comes from the same ExportSpec definitions, so the CSV route and the
direct-PostgreSQL route return identical tables.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from config.settings import PROJECT_ROOT
from powerbi.export_powerbi_datasets import DEFAULT_OUTPUT_DIR, MANIFEST_NAME, export_specs

OUT_PATH = PROJECT_ROOT / "powerbi" / "documentation" / "power_query.m"

HEADER = r"""// =============================================================================
// Hospital Intelligence - Dashboard A - Power Query (M)
// =============================================================================
// GENERATED by powerbi/generate_power_query.py from manifest.json and the export
// specs in powerbi/export_powerbi_datasets.py. Do not edit by hand.
//
// HOW TO USE (Power BI Desktop > Transform data > Power Query Editor)
//   1. Create the four parameters below: Home > Manage Parameters > New, or
//      New Source > Blank Query > Advanced Editor, paste the body, and rename
//      the query to the name shown in the "Query:" line.
//   2. Create the function query fnLoadTable the same way.
//   3. Create one blank query per table and paste its body; the query name must
//      equal the table name (fact_admissions, dim_patient, ...), because the DAX
//      measures refer to these names.
//   4. Create the _Measures query (an empty table that holds all measures).
//   5. Close & Apply.
//
// SOURCE MODES (parameter SourceMode)
//   "CSV"        : reads <DataFolder>\<table>.csv written by
//                  .venv/bin/python -m powerbi.export_powerbi_datasets
//   "PostgreSQL" : runs the same SELECT statements directly against the
//                  warehouse with PostgreSQL.Database + Value.NativeQuery
//                  (Power BI asks once to approve native database queries).
//
// TYPES: every column gets an explicit type. timestamptz columns
// (ingestion/benchmark audit times) are converted to UTC and typed datetime so
// the freshness measures compare against UTCNOW(). Clinical timestamps are
// MIMIC de-identified, date-shifted values (years 2110-2201): they are valid
// for intervals within a patient, NOT for calendar trends.
//
// STATUS: written to spec but NOT executed in Power BI (no Power BI Desktop in
// the build environment). The column lists were generated from the real export.
// =============================================================================


// ---------------------------------------------------------------- parameters
// Query: SourceMode
"CSV" meta [IsParameterQuery = true, List = {"CSV", "PostgreSQL"}, DefaultValue = "CSV", Type = "Text", IsParameterQueryRequired = true]

// Query: DataFolder   (folder that holds the exported CSV files, no trailing slash)
"C:\HospitalIntel\powerbi\datasets" meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = true]

// Query: PgServer   (host:port of the PostgreSQL warehouse)
"localhost:5433" meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = true]

// Query: PgDatabase
"hospital_intel" meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = true]


// ------------------------------------------------------------------ function
// Query: fnLoadTable
// Loads one table from CSV or PostgreSQL, sets explicit column types, and
// converts timestamptz columns to UTC datetime.
(tableName as text, nativeSql as text, columnTypes as list, utcColumns as list) as table =>
let
    Raw =
        if SourceMode = "PostgreSQL" then
            Value.NativeQuery(
                PostgreSQL.Database(PgServer, PgDatabase),
                nativeSql,
                null,
                [EnableFolding = true]
            )
        else
            let
                Path = Text.TrimEnd(DataFolder, {"\", "/"}) & "\" & tableName & ".csv",
                Csv = Csv.Document(
                    File.Contents(Path),
                    [Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]
                ),
                Promoted = Table.PromoteHeaders(Csv, [PromoteAllScalars = true]),
                // CSV empty field = SQL NULL
                Nulls = Table.ReplaceValue(
                    Promoted, "", null, Replacer.ReplaceValue, Table.ColumnNames(Promoted)
                )
            in
                Nulls,
    // en-US culture: '.' decimal separator and ISO-8601 timestamps parse the same
    // on any regional setting; "true"/"false" parse to logical.
    Typed = Table.TransformColumnTypes(Raw, columnTypes, "en-US"),
    Utc = Table.TransformColumns(
        Typed,
        List.Transform(
            utcColumns,
            (c) => {c, each if _ = null then null else DateTimeZone.RemoveZone(DateTimeZone.ToUtc(_)), type datetime}
        )
    )
in
    Utc


// ------------------------------------------------------------ measure table
// Query: _Measures
// Empty table that holds every DAX measure. After loading, hide its column;
// Power BI then shows _Measures at the top of the Fields pane.
let
    Source = #table(type table [#"Measure Holder" = text], {})
in
    Source
"""


def _m_string(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def render(manifest: dict) -> str:
    specs = {s.name: s for s in export_specs()}
    parts = [HEADER]
    group = None
    for name, entry in manifest["tables"].items():
        spec = specs[name]
        if spec.role != group:
            group = spec.role
            parts.append(f"\n// {'-' * 60} {group} tables\n")
        sql = " ".join(spec.query.split())
        types = ",\n        ".join(
            f"{{{_m_string(c['name'])}, {c['power_query_type']}}}" for c in entry["columns"]
        )
        utc = ", ".join(_m_string(c["name"]) for c in entry["columns"]
                        if c["type"] == "timestamptz")
        note = f"\n// Note: {entry['note']}" if entry.get("note") else ""
        parts.append(
            f"// Query: {name}\n"
            f"// Grain: {entry['grain']}. Source: {entry['source']}. "
            f"Rows at export: {entry['rows']:,}.{note}\n"
            "let\n"
            "    Source = fnLoadTable(\n"
            f"        {_m_string(name)},\n"
            f"        {_m_string(sql)},\n"
            "        {\n"
            f"        {types}\n"
            "        },\n"
            f"        {{{utc}}}\n"
            "    )\n"
            "in\n"
            "    Source\n"
        )
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--manifest", type=Path, default=DEFAULT_OUTPUT_DIR / MANIFEST_NAME)
    parser.add_argument("--output", type=Path, default=OUT_PATH)
    args = parser.parse_args(argv)
    manifest = json.loads(args.manifest.read_text())
    args.output.write_text(render(manifest))
    print(f"Wrote {args.output} ({len(manifest['tables'])} table queries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
