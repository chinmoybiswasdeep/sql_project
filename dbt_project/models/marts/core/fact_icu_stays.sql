-- Grain: one row per ICU stay (stay_id).
select
    stay_id,
    hadm_id,
    subject_id,
    first_careunit,
    last_careunit,
    first_unit_type,
    changed_icu_unit,
    intime,
    outtime,
    icu_los_hours,
    icu_los_days,
    {{ los_band('icu_los_days') }}                 as icu_los_band,
    icu_stay_seq,
    icu_stay_seq > 1                               as is_repeat_icu_stay_same_admission,
    hours_since_prev_icu_discharge,
    hours_from_admit_to_icu,
    is_outside_admission_window,
    died_in_icu,
    died_in_hospital,
    age_at_admission,
    age_group,
    sex,
    admission_type,
    admission_group,
    patient_total_admissions,
    patient_total_admissions > 1                   as patient_has_multiple_admissions
from {{ ref('int_icu_stays_enriched') }}
